function buildExportDoc(input: MobileScaffoldInput): string {
  return `# Android-Export — Schritt für Schritt

1. **Godot 4.3+** von godotengine.org laden (keine Installation nötig).
2. Projekt öffnen: Godot-Projektmanager → Importieren → \`project.godot\` in diesem Ordner.
3. **Android Build Template**: Editor → Projekt → "Android-Build-Vorlage installieren".
4. **Export-Vorlagen**: Editor → Editor-Einstellungen → Export → Android: Pfade zu Android SDK + JDK setzen (Android Studio liefert beides).
5. **Debug-Export**: Projekt → Export → Android → "Projekt exportieren" → APK aufs Gerät (USB-Debugging) und testen.
6. **Release-Signing**: Keystore erzeugen (\`keytool -genkey ...\`), in Godot unter Export → Android → Keystore eintragen. **Keystore + Passwörter niemals ins Repo!**
7. **Play Store**: AAB exportieren (\`gradle_build/use_gradle_build=true\`), in der Play Console als Internal Testing Track hochladen, Pre-Launch-Report prüfen.
8. Paket-ID ist **${input.packageId}** — nach dem ersten Upload nicht mehr änderbar.

Checklisten (App-Store + Datenschutz) in Empire Game Forge unter „Checklisten" abarbeiten, bevor irgendetwas veröffentlicht wird.
`;
}

function buildPerformanceDoc(budget: MobilePerformanceBudget, genre: Genre): string {
  return `# Performance-Budget (${genre})

| Metrik | Budget |
| --- | --- |
| Ziel-FPS | ${budget.targetFps} |
| Speicher (RAM) | max. ${budget.maxMemoryMb} MB |
| APK/AAB-Größe | max. ${budget.maxApkSizeMb} MB |
| Kaltstart | max. ${budget.maxColdStartSeconds} s |
| Draw Calls | max. ${budget.maxDrawCalls} |

Regeln, die dieses Template bereits umsetzt:
- Objekt-Pooling statt ständigem Instanziieren (siehe Runner-Spawner).
- Mobile-Renderer, ein CanvasLayer, programmatische UI ohne große Texturen.
- Autosave nur bei Pause/Beenden statt jedem Frame.

Beim Erweitern: Godot-Profiler (Debugger → Profiler) auf dem ECHTEN Zielgerät
laufen lassen, Texturen als komprimierte Formate importieren, Partikel deckeln.
`;
}

export function buildGodotScaffold(input: MobileScaffoldInput): ScaffoldFile[] {
  const withMonetization = input.monetization.some((m) =>
    ['rewarded_ads', 'interstitial_ads', 'iap_consumables', 'iap_non_consumables', 'battle_pass', 'cosmetics', 'subscription'].includes(m),
  );
  const gameplay = gameplayFor(input.genre);
  const budget = defaultPerformanceBudget(input.genre);

  const files: ScaffoldFile[] = [
    { path: 'project.godot', content: buildProjectGodot(input, withMonetization) },
    { path: 'scenes/main.tscn', content: mainTscn() },
    { path: 'scenes/gameplay.tscn', content: gameplayTscn(gameplay.scriptFile) },
    { path: 'scripts/main.gd', content: MAIN_GD },
    { path: `scripts/${gameplay.scriptFile}`, content: gameplay.script },
    { path: 'scripts/autoload/game_state.gd', content: GAME_STATE_GD },
    { path: 'scripts/autoload/audio_manager.gd', content: AUDIO_MANAGER_GD },
    { path: 'scripts/autoload/analytics.gd', content: ANALYTICS_GD },
    { path: 'export_presets.cfg.example', content: buildExportPresetsExample(input, budget) },
    { path: 'docs/EXPORT_ANDROID.md', content: buildExportDoc(input) },
    { path: 'docs/PERFORMANCE.md', content: buildPerformanceDoc(budget, input.genre) },
    {
      path: 'README.md',
      content: `# ${input.projectName} — Godot-Projekt

Generiert von Empire Game Forge AI (Godot 4.3, GDScript, Touch-first).

- Öffnen: Godot-Projektmanager → Importieren → \`project.godot\`
- Starten: F5 (Hauptszene \`scenes/main.tscn\`)
- Gameplay-Template: \`scripts/${gameplay.scriptFile}\` (Genre: ${input.genre})
- Save-System: \`scripts/autoload/game_state.gd\` (JSON in \`user://save.json\`)
- Android-Export: \`docs/EXPORT_ANDROID.md\` · Performance: \`docs/PERFORMANCE.md\`
`,
    },
    { path: '.gitignore', content: 'build/\n.godot/\nexport_presets.cfg\n*.keystore\n' },
  ];
  if (withMonetization) {
    files.push({ path: 'scripts/autoload/monetization.gd', content: MONETIZATION_GD });
  }
  return files;
}
