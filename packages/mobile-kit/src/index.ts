import type { Genre, MobilePerformanceBudget, MonetizationModel, ScaffoldFile } from '@egf/core';
import {
  ANALYTICS_GD,
  AUDIO_MANAGER_GD,
  GAME_STATE_GD,
  GAMEPLAY_IDLE_GD,
  GAMEPLAY_PUZZLE_GD,
  GAMEPLAY_RUNNER_GD,
  MAIN_GD,
  MONETIZATION_GD,
  gameplayTscn,
  mainTscn,
} from './gdTemplates';

export interface MobileScaffoldInput {
  projectName: string;
  slug: string;
  genre: Genre;
  packageId: string;
  orientation: 'portrait' | 'landscape' | 'sensor';
  targetFps: number;
  monetization: MonetizationModel[];
}

export function defaultPackageId(slug: string): string {
  const cleaned = slug
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '')
    .replace(/^[0-9]+/, '');
  return `com.empireforge.${cleaned || 'game'}`;
}

export function defaultPerformanceBudget(genre: Genre): MobilePerformanceBudget {
  switch (genre) {
    case 'hypercasual':
    case 'runner':
    case 'merge':
    case 'puzzle':
      return { targetFps: 60, maxMemoryMb: 300, maxApkSizeMb: 60, maxColdStartSeconds: 3, maxDrawCalls: 120 };
    case 'idle':
    case 'tycoon':
    case 'simulator':
    case 'hybridcasual':
    case 'card_battler':
      return { targetFps: 60, maxMemoryMb: 400, maxApkSizeMb: 100, maxColdStartSeconds: 4, maxDrawCalls: 200 };
    case 'rpg_lite':
    case 'survival':
    case 'roguelite':
    case 'tower_defense':
    case 'battle_arena':
    case 'racing':
    case 'sports':
    case 'sandbox':
      return { targetFps: 30, maxMemoryMb: 500, maxApkSizeMb: 150, maxColdStartSeconds: 5, maxDrawCalls: 300 };
    default:
      return { targetFps: 60, maxMemoryMb: 400, maxApkSizeMb: 100, maxColdStartSeconds: 4, maxDrawCalls: 200 };
  }
}

type GameplayTemplate = { scriptFile: string; script: string };

function gameplayFor(genre: Genre): GameplayTemplate {
  const runnerLike: Genre[] = ['runner', 'hypercasual', 'racing', 'obby', 'sports'];
  const idleLike: Genre[] = ['idle', 'tycoon', 'simulator', 'merge', 'hybridcasual', 'sandbox'];
  if (runnerLike.includes(genre)) return { scriptFile: 'gameplay_runner.gd', script: GAMEPLAY_RUNNER_GD };
  if (idleLike.includes(genre)) return { scriptFile: 'gameplay_idle.gd', script: GAMEPLAY_IDLE_GD };
  return { scriptFile: 'gameplay_puzzle.gd', script: GAMEPLAY_PUZZLE_GD };
}

function orientationSetting(orientation: MobileScaffoldInput['orientation']): number {
  // Godot DisplayServer.ScreenOrientation: 0 landscape, 1 portrait, 6 sensor.
  return orientation === 'landscape' ? 0 : orientation === 'portrait' ? 1 : 6;
}

function buildProjectGodot(input: MobileScaffoldInput, withMonetization: boolean): string {
  const autoloads = [
    'GameState="*res://scripts/autoload/game_state.gd"',
    'AudioManager="*res://scripts/autoload/audio_manager.gd"',
    'Analytics="*res://scripts/autoload/analytics.gd"',
    ...(withMonetization ? ['Monetization="*res://scripts/autoload/monetization.gd"'] : []),
  ].join('\n');

  return `; Engine configuration - generated by Empire Game Forge AI (Godot 4.3)
config_version=5

[application]

config/name="${input.projectName}"
config/version="0.1.0"
run/main_scene="res://scenes/main.tscn"
config/features=PackedStringArray("4.3", "Mobile")

[autoload]

${autoloads}

[display]

window/size/viewport_width=720
window/size/viewport_height=1280
window/handheld/orientation=${orientationSetting(input.orientation)}
window/stretch/mode="canvas_items"
window/stretch/aspect="expand"

[rendering]

renderer/rendering_method="mobile"
renderer/rendering_method.mobile="mobile"

[input_devices]

pointing/emulate_touch_from_mouse=true
`;
}

